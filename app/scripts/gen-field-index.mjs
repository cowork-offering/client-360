#!/usr/bin/env node
/* =============================================================================
   THE FIELD INDEX GENERATOR.

   Turns the live-describe inventory (knowledge/sf-build-v2/field-inventory-*.json,
   pulled from the org's own describe) into a compact module the workroom bundles,
   so the room can PROPOSE fields it has no curated vocabulary for — "did you mean
   Payment Schedule? The org offers Monthly, Quarterly, …" — before the banker
   ever confirms anything. The index is a snapshot by design: regenerating it is
   re-running the describe pull plus this script, and the org remains the
   authority at stage time regardless of what this file believes.

   Usage: node scripts/gen-field-index.mjs [inventory.json] [out.ts]
   ============================================================================= */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const inventoryPath = resolve(process.argv[2] ?? resolve(here, "../../knowledge/sf-build-v2/field-inventory-20260831.json"));
const outPath = resolve(process.argv[3] ?? resolve(here, "../src/workroom/fieldIndex.gen.ts"));

const inventory = JSON.parse(readFileSync(inventoryPath, "utf8"));

/** Fields the doctrine keeps out of the wave, mirrored from the org-side deny list
 *  (StageLoanModification.FIELD_WAVE_DENY). The index never proposes what the
 *  stage would refuse. */
const DENY = new Set([
  "llc_bi__amount__c", "llc_bi__maturity_date__c", "llc_bi__interestrate__c", "llc_bi__term_months__c",
  "llc_bi__stage__c", "llc_bi__status__c",
  "llc_bi__account__c", "llc_bi__product_package__c", "llc_bi__parentloan__c",
  "llc_bi__originalparentloan__c", "llc_bi__highest__c", "llc_bi__lookupkey__c",
  "llc_bi__isrenewal__c", "llc_bi__is_modification__c", "llc_bi__is_no_action_placeholder__c",
  "llc_bi__is_original_inactive_loan__c", "ownerid", "recordtypeid", "currencyisocode",
]);

/** Lookups re-anchor and the stage refuses them; system/audit noise never helps a proposal. */
function proposable(f) {
  if (DENY.has(f.name.toLowerCase())) return false;
  if (f.referenceTo?.length) return false;
  if (/^(Integration_|Migration_|cm_Roll_Up|LLC_BI__CRA_|LLC_BI__HMDA_)/i.test(f.name)) return false;
  return true;
}

const rows = (inventory["LLC_BI__Loan__c"] ?? []).filter(proposable).map((f) => {
  const row = [f.name, f.label, f.type];
  if (f.values?.length) row.push(f.values);
  return row;
});

const stamp = inventoryPath.match(/(\d{8})/)?.[1] ?? "unknown";
const body = `/* GENERATED by scripts/gen-field-index.mjs from the live describe (${stamp}) — do not edit.
   Regenerate: pull the inventory (see knowledge/sf-build-v2/OBJECT-COVERAGE.md) and re-run the script.
   The org is the authority at stage time; this index only lets the room PROPOSE. */

/** [apiName, label, type, picklistValues?] */
export type IndexedField = [string, string, string, string[]?];

export const FIELD_INDEX_STAMP = "${stamp}";

export const LOAN_FIELD_INDEX: IndexedField[] = ${JSON.stringify(rows, null, 0)};
`;

writeFileSync(outPath, body);
console.log(`field index: ${rows.length} proposable loan fields -> ${outPath}`);
